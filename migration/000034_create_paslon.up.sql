CREATE TABLE IF NOT EXISTS paslon (
    id_paslon BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_pemira BIGINT NOT NULL REFERENCES pemira(id_pemira) ON DELETE CASCADE,
    nomor_urut INT NOT NULL,
    nim_ketua VARCHAR(20) NOT NULL,
    nama_ketua VARCHAR(100) NOT NULL,
    nim_wakil VARCHAR(20) NOT NULL,
    nama_wakil VARCHAR(100) NOT NULL,
    nama_kabinet VARCHAR(100) NOT NULL,
    foto_paslon VARCHAR(255),
    visi TEXT,
    misi TEXT,
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diperbarui_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
