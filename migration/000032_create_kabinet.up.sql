CREATE TABLE IF NOT EXISTS kabinet (
    id_kabinet BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nama_kabinet VARCHAR(100) NOT NULL,
    tahun_mulai INT NOT NULL,
    tahun_selesai INT NOT NULL,
    logo_kabinet VARCHAR(255),
    visi TEXT,
    misi TEXT,
    is_aktif BOOLEAN NOT NULL DEFAULT FALSE,
    tanggal_mulai DATE,
    tanggal_demis DATE,
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diperbarui_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
