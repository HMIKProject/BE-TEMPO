CREATE TABLE IF NOT EXISTS anggota (
    id_anggota BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_pengguna BIGINT REFERENCES pengguna(id_pengguna) ON DELETE SET NULL,
    nim VARCHAR(20) NOT NULL UNIQUE,
    nama_lengkap VARCHAR(100) NOT NULL,
    foto_profil VARCHAR(255),
    program_studi VARCHAR(100) NOT NULL,
    angkatan INT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Pengurus',
    tautan VARCHAR(255),
    files VARCHAR(255),
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diubah_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);