CREATE TABLE IF NOT EXISTS riwayat_jabatan (
    id_riwayat BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_anggota BIGINT NOT NULL REFERENCES anggota(id_anggota) ON DELETE CASCADE,
    nim VARCHAR(20) NOT NULL,
    periode VARCHAR(50) NOT NULL,
    jabatan VARCHAR(100) NOT NULL,
    nama_departemen VARCHAR(100) DEFAULT '',
    nama_divisi VARCHAR(100) DEFAULT '',
    status VARCHAR(50) NOT NULL DEFAULT 'Demisioner',
    dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_riwayat_jabatan_id_anggota ON riwayat_jabatan(id_anggota);
CREATE INDEX IF NOT EXISTS idx_riwayat_jabatan_nim ON riwayat_jabatan(nim);
