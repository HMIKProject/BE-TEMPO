CREATE TABLE IF NOT EXISTS pemira (
    id_pemira BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tahun_periode VARCHAR(50) NOT NULL,
    tanggal_mulai TIMESTAMP NOT NULL,
    tanggal_selesai TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diperbarui_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
