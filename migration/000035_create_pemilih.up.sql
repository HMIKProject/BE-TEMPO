CREATE TABLE IF NOT EXISTS pemilih (
    id_pemilih BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_pemira BIGINT NOT NULL REFERENCES pemira(id_pemira) ON DELETE CASCADE,
    nim VARCHAR(20) NOT NULL,
    email_kampus VARCHAR(100) NOT NULL,
    status_memilih BOOLEAN NOT NULL DEFAULT FALSE,
    kode_otp VARCHAR(10),
    otp_expired TIMESTAMP,
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diperbarui_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pemilih_nim_pemira UNIQUE (id_pemira, nim)
);
